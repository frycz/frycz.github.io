// Articles whose source lives in another repository. The file under content/blog is a copy this
// script writes; the source is the one to edit. Run `npm run sync:articles` after changing a
// source, and `npm run sync:articles -- --check` to find out whether a copy has fallen behind.
//
// The copy is committed, because the build on CI checks out this repository alone and has no way
// to reach the sources. That is also why a missing source is a skip rather than an error.

const crypto = require("node:crypto");
const fs = require("node:fs");
const path = require("node:path");

const ROOT = path.resolve(__dirname, "..");
const OUT_DIR = path.join(ROOT, "content", "blog");

// source: relative to this repository, so the manifest says nothing about one machine's layout.
// date: the publication date, and the order of the blog list. It stays as it is when the source changes.
const ARTICLES = [
  {
    source: "../composite-agents/modular-agent.md",
    slug: "modular-agent",
    title: "Modular Agent Architecture",
    date: "2026-11-22",
    description:
      "The components an LLM agent consists of, the interfaces between them, and how they compose: " +
      "a model, a harness and tools that each change for one reason and can be replaced on their own.",
  },
];

// The title is rendered by the page's header, so the document's own H1 would be the second one.
function stripTitle(markdown) {
  const lines = markdown.split("\n");
  const first = lines.findIndex((line) => line.trim() !== "");
  if (first === -1 || !/^#\s+/.test(lines[first])) return markdown;
  let next = first + 1;
  while (next < lines.length && lines[next].trim() === "") next++;
  return lines.slice(next).join("\n");
}

function quote(value) {
  return `"${String(value).replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;
}

function render(article, source) {
  const hash = crypto.createHash("sha256").update(source).digest("hex").slice(0, 16);
  const frontmatter = [
    `title: ${quote(article.title)}`,
    `date: ${quote(article.date)}`,
    `slug: ${quote(article.slug)}`,
    `description: ${quote(article.description)}`,
    `source: ${quote(article.source)}`,
    `sourceHash: ${quote(hash)}`,
    `generated: ${quote("scripts/sync-articles.js — do not edit this file, edit the source")}`,
  ];
  const body = stripTitle(source).replace(/\s*$/, "\n");
  return `---\n${frontmatter.join("\n")}\n---\n\n${body}`;
}

function main() {
  const check = process.argv.includes("--check");
  let drifted = 0;

  for (const article of ARTICLES) {
    const sourcePath = path.resolve(ROOT, article.source);
    const outPath = path.join(OUT_DIR, `${article.slug}.md`);
    const shown = path.relative(ROOT, outPath);

    if (!fs.existsSync(sourcePath)) {
      console.log(`skip     ${shown} — source not found at ${article.source}`);
      continue;
    }

    const wanted = render(article, fs.readFileSync(sourcePath, "utf8"));
    const current = fs.existsSync(outPath) ? fs.readFileSync(outPath, "utf8") : null;

    if (current === wanted) {
      console.log(`current  ${shown}`);
      continue;
    }

    if (check) {
      drifted++;
      console.log(`behind   ${shown} — ${current === null ? "missing" : "differs from"} ${article.source}`);
      continue;
    }

    fs.mkdirSync(OUT_DIR, { recursive: true });
    fs.writeFileSync(outPath, wanted);
    const words = wanted.split(/\s+/).length;
    console.log(`${current === null ? "created " : "updated "} ${shown} — ${words} words from ${article.source}`);
  }

  if (drifted) {
    console.log(`\n${drifted} ${drifted === 1 ? "article is" : "articles are"} behind. Run: npm run sync:articles`);
    process.exitCode = 1;
  }
}

main();
